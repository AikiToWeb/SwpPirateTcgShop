CREATE TABLE IF NOT EXISTS cards (
  id VARCHAR(40) PRIMARY KEY, name VARCHAR(200) NOT NULL, en VARCHAR(200) NOT NULL,
  set_name VARCHAR(200) NOT NULL, price BIGINT NOT NULL CHECK(price >= 0),
  stock INTEGER NOT NULL CHECK(stock >= 0), image VARCHAR(200) NOT NULL,
  game VARCHAR(80) NOT NULL DEFAULT '', card_condition VARCHAR(20) NOT NULL DEFAULT 'NM',
  language VARCHAR(30) NOT NULL DEFAULT '한국어', created BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS shop_users (id VARCHAR(80) PRIMARY KEY, nickname VARCHAR(80) NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (
  token VARCHAR(64) PRIMARY KEY, user_id VARCHAR(80) NOT NULL REFERENCES shop_users(id),
  csrf VARCHAR(100) NOT NULL, expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS oauth_states (token VARCHAR(64) PRIMARY KEY, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS binders (
  user_id VARCHAR(80) REFERENCES shop_users(id), card_id VARCHAR(40) REFERENCES cards(id),
  PRIMARY KEY(user_id,card_id)
);
CREATE TABLE IF NOT EXISTS carts (
  user_id VARCHAR(80) REFERENCES shop_users(id), card_id VARCHAR(40) REFERENCES cards(id),
  quantity INTEGER NOT NULL CHECK(quantity > 0), PRIMARY KEY(user_id,card_id)
);
CREATE TABLE IF NOT EXISTS shop_orders (
  id VARCHAR(40) PRIMARY KEY, user_id VARCHAR(80) NOT NULL REFERENCES shop_users(id),
  request_key VARCHAR(80) NOT NULL, status VARCHAR(20) NOT NULL, total BIGINT NOT NULL CHECK(total>=0),
  created BIGINT NOT NULL, UNIQUE(user_id,request_key)
);
CREATE TABLE IF NOT EXISTS order_items (
  order_id VARCHAR(40) REFERENCES shop_orders(id), card_id VARCHAR(40) REFERENCES cards(id),
  name VARCHAR(200) NOT NULL, price BIGINT NOT NULL CHECK(price>=0), quantity INTEGER NOT NULL CHECK(quantity>0),
  PRIMARY KEY(order_id,card_id)
);
CREATE TABLE IF NOT EXISTS shop_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, game VARCHAR(80) NOT NULL,
  title VARCHAR(200) NOT NULL, starts_at TIMESTAMP NOT NULL, description VARCHAR(1000) NOT NULL,
  is_sample BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS migration_history (name VARCHAR(100) PRIMARY KEY, applied BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires);
CREATE INDEX IF NOT EXISTS idx_orders_user ON shop_orders(user_id,created);
ALTER TABLE cards ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE cards ADD COLUMN IF NOT EXISTS is_sample BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE shop_users ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER';
ALTER TABLE shop_events ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE shop_orders ADD COLUMN IF NOT EXISTS is_sample BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS games (name VARCHAR(80) PRIMARY KEY, sort_order INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id VARCHAR(40) NOT NULL REFERENCES cards(id), actor_id VARCHAR(80) NOT NULL REFERENCES shop_users(id),
  delta INTEGER NOT NULL, balance INTEGER NOT NULL CHECK(balance>=0),
  reason VARCHAR(300) NOT NULL, order_id VARCHAR(40), created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_stock_card ON stock_movements(card_id,created);
